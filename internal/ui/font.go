// aliases: lo que no está en la fuente se traduce a algo que sí está, en vez
// de salir un cuadro vacío. Así "Economía" y "ECONOMÍA" se ven igual.
var fontAliases = map[rune]rune{
	'á': 'A', 'é': 'E', 'í': 'I', 'ó': 'O', 'ú': 'U', 'ü': 'U', 'ñ': 'N',
	'Á': 'A', 'É': 'E', 'Í': 'I', 'Ó': 'O', 'Ú': 'U', 'Ü': 'U', 'Ñ': 'N',
	'à': 'A', 'è': 'E', 'ì': 'I', 'ò': 'O', 'ù': 'U',
	'×': 'x', '✕': 'x', '✓': 'V', '✔': 'V', '⚠': '!', '«': '<', '»': '>',
	'“': '"', '”': '"', '‘': '\'', '’': '\'', '–': '-', '—': '-', '…': '.',
	'¿': '?', '¡': '!', '•': '·', '▪': '·', '▸': '>', '→': '→',
}

// glyphFor devuelve las 7 filas de un carácter (mayúsculas y alias incluidos).
func glyphFor(r rune) (string, bool) {
	if r >= 'a' && r <= 'z' {
		r = r - 'a' + 'A'
	}
	if alias, ok := fontAliases[r]; ok {
		r = alias
	}
	g, ok := font[r]
	return g, ok
}

// TextWidth devuelve el ancho en "píxeles de fuente" de un texto (1 píxel de
// separación entre caracteres).
func TextWidth(text string) int {
	n := 0
	for range text {
		n++
	}
	if n == 0 {
		return 0
	}
	return n*glyphW + (n - 1)
}

// drawText pinta `text` en la imagen a partir de (x, y) con el tamaño `scale`.
// Solo se pintan los píxeles encendidos: el fondo se respeta (si se pintaran
// también los apagados, cada carácter saldría como un rectángulo sólido).
// Los caracteres desconocidos se pintan como '?'.
func drawText(img drawTarget, text string, x, y, scale int, on colorValue) {
	cx := x
	for _, r := range text {
		g, ok := glyphFor(r)
		if !ok {
			g = font['?']
		}
		rows := strings.Split(g, "/")
		for ry := 0; ry < glyphH && ry < len(rows); ry++ {
			row := rows[ry]
			for rx := 0; rx < glyphW && rx < len(row); rx++ {
				if row[rx] == '#' {
					img.fillRect(cx+rx*scale, y+ry*scale, scale, scale, on)
				}
			}
		}
		cx += (glyphW + 1) * scale
	}
}
